create or replace function public.save_site_content(p_items jsonb)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if p_items is null or jsonb_typeof(p_items) is distinct from 'array' then
    raise exception 'Invalid content item list.';
  end if;

  if jsonb_array_length(p_items) <> (select count(*) from public.site_content) then
    raise exception 'Invalid content item count.';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_items) as item(
      id text,
      kind text,
      title text,
      body text,
      sort_order integer,
      is_active boolean
    )
    group by item.id
    having count(*) > 1
  )
  or exists (
    select 1
    from jsonb_to_recordset(p_items) as item(
      id text,
      kind text,
      title text,
      body text,
      sort_order integer,
      is_active boolean
    )
    left join public.site_content as current_item
      on current_item.id = item.id
    where current_item.id is null
      or current_item.kind is distinct from item.kind
      or item.title is null
      or length(btrim(item.title)) not between 2 and 120
      or item.body is null
      or length(btrim(item.body)) not between 2 and 300
      or item.sort_order is null
      or item.sort_order < 0
      or item.is_active is null
  )
  or exists (
    select item.sort_order
    from jsonb_to_recordset(p_items) as item(
      id text,
      kind text,
      title text,
      body text,
      sort_order integer,
      is_active boolean
    )
    group by item.sort_order
    having count(*) > 1
  )
  then
    raise exception 'Invalid content item data.';
  end if;

  update public.site_content as current_item
  set
    title = item.title,
    body = item.body,
    sort_order = item.sort_order,
    is_active = item.is_active,
    updated_at = now()
  from jsonb_to_recordset(p_items) as item(
    id text,
    kind text,
    title text,
    body text,
    sort_order integer,
    is_active boolean
  )
  where current_item.id = item.id;
end;
$$;

revoke all on function public.save_site_content(jsonb)
  from public, anon, authenticated;
grant execute on function public.save_site_content(jsonb)
  to service_role;
