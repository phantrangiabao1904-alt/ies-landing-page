create table if not exists public.request_rate_limits (
  key_hash text primary key check (length(key_hash) = 64),
  window_started_at timestamptz not null,
  request_count integer not null check (request_count > 0),
  updated_at timestamptz not null default now()
);

alter table public.request_rate_limits enable row level security;
revoke all on table public.request_rate_limits from anon, authenticated, service_role;
create index if not exists request_rate_limits_window_started_at_idx
  on public.request_rate_limits (window_started_at);

create or replace function public.consume_request_rate_limit(
  p_key_hash text,
  p_max_requests integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  current_count integer;
begin
  if p_key_hash !~ '^[0-9a-f]{64}$'
    or p_max_requests < 1
    or p_max_requests > 10000
    or p_window_seconds < 1
    or p_window_seconds > 86400
  then
    raise exception 'Invalid rate limit parameters.';
  end if;

  insert into public.request_rate_limits (
    key_hash,
    window_started_at,
    request_count,
    updated_at
  )
  values (p_key_hash, now(), 1, now())
  on conflict (key_hash) do update
  set
    request_count = case
      when public.request_rate_limits.window_started_at
        <= now() - make_interval(secs => p_window_seconds)
      then 1
      else public.request_rate_limits.request_count + 1
    end,
    window_started_at = case
      when public.request_rate_limits.window_started_at
        <= now() - make_interval(secs => p_window_seconds)
      then now()
      else public.request_rate_limits.window_started_at
    end,
    updated_at = now()
  returning request_count into current_count;

  delete from public.request_rate_limits
  where key_hash in (
    select expired.key_hash
    from public.request_rate_limits as expired
    where expired.window_started_at < now() - interval '7 days'
    order by expired.window_started_at
    limit 100
  );

  return current_count <= p_max_requests;
end;
$$;

revoke all on function public.consume_request_rate_limit(text, integer, integer)
  from public, anon, authenticated;
grant execute on function public.consume_request_rate_limit(text, integer, integer)
  to service_role;

