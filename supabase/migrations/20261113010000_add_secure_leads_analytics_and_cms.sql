create or replace function public.get_analytics_summary(p_since timestamptz)
returns jsonb
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  with daily_events as (
    select
      date_trunc('day', created_at)::date as day,
      count(*) filter (where event_type = 'page_view') as page_views,
      count(*) filter (where event_type = 'form_click') as form_clicks,
      count(*) filter (where event_type = 'lead_submit') as lead_submits
    from public.analytics_events
    where created_at >= p_since
    group by 1
  ),
  referrals as (
    select source, count(*) as count
    from public.analytics_events
    where event_type = 'page_view'
      and created_at >= p_since
    group by source
    order by count desc
    limit 10
  ),
  funnel as (
    select
      count(*) filter (where event_type = 'page_view') as page_views,
      count(*) filter (where event_type = 'form_click') as form_clicks,
      count(*) filter (where event_type = 'lead_submit') as lead_submits
    from public.analytics_events
    where created_at >= p_since
  )
  select jsonb_build_object(
    'daily',
    coalesce(
      (
        select jsonb_agg(
          jsonb_build_object(
            'date', days.day::text,
            'page_views', coalesce(daily_events.page_views, 0),
            'form_clicks', coalesce(daily_events.form_clicks, 0),
            'lead_submits', coalesce(daily_events.lead_submits, 0)
          )
          order by days.day
        )
        from generate_series(
          date_trunc('day', p_since)::date,
          current_date,
          interval '1 day'
        ) as days(day)
        left join daily_events on daily_events.day = days.day::date
      ),
      '[]'::jsonb
    ),
    'referrals',
    coalesce(
      (
        select jsonb_agg(
          jsonb_build_object('source', source, 'count', count)
          order by count desc
        )
        from referrals
      ),
      '[]'::jsonb
    ),
    'funnel',
    (
      select jsonb_build_object(
        'page_views', page_views,
        'form_clicks', form_clicks,
        'lead_submits', lead_submits
      )
      from funnel
    )
  );
$$;

revoke all on function public.get_analytics_summary(timestamptz)
  from public, anon, authenticated;
grant execute on function public.get_analytics_summary(timestamptz)
  to service_role;

